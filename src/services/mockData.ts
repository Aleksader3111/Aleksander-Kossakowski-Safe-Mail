// Pre-evaluate all mock emails so reports, priorities and document extractions are immediately available
export function getInitialEmailsWithReports(): EmailMessage[] {
  return INITIAL_MOCK_EMAILS.map(mail => {
    const report = evaluateEmailSecurity({
      id: mail.id,
      from: mail.from,
      to: mail.to,
      subject: mail.subject,
      bodySnippet: mail.bodySnippet,
      fullBody: mail.fullBody,
      headers: mail.rawHeaders,
      attachments: mail.id === 'msg-fake-invoice-07' ? [{ filename: 'faktura_vat.pdf.exe', mimeType: 'application/x-msdownload', sizeBytes: 245000 }] : [],
    });

    const priority = evaluateEmailPriority({
      id: mail.id,
      subject: mail.subject,
      from: mail.from,
      bodySnippet: mail.bodySnippet,
      fullBody: mail.fullBody,
      category: report.category,
      overallRisk: report.overallRisk,
    });

    const doc = parseDocumentFromEmail({
      id: mail.id,
      subject: mail.subject,
      from: mail.from,
      bodySnippet: mail.bodySnippet,
      fullBody: mail.fullBody,
    });

    return {
      ...mail,
      securityReport: report,
      priorityAssessment: priority,
      documentExtraction: doc || undefined,
    };
  });
}

